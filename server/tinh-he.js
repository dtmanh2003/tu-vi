/** Tìm tinh hệ của một cung (theo tên chính tinh tiếng Việt). */
const norm = (names) => [...names].sort().join('+');
const BY_SET = Object.fromEntries(Object.entries(TINH_HE).map(([k, v]) => [norm(k.split('+')), v]));

export function findTinhHe(palace) {
  const names = palace.majorStars.map((s) => s.name);
  if (!names.length) return null;
  const hit = BY_SET[norm(names)];
  if (hit) return { key: names.join(' – '), ...hit };
  // Không có cặp: dùng sao đầu tiên
  return TINH_HE[names[0]] ? { key: names[0], ...TINH_HE[names[0]] } : null;
}

